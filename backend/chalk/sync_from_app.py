"""Vendor the app's forecast code, trained artifacts and history into ``src/vendor/``.

Run from ``backend/`` with the APP's environment, before ``chalk apply``:

    uv run python chalk/sync_from_app.py

Copies ``clearinghouse/forecast/{features,model,provider}.py`` (two import lines rewritten so the
copies are self-contained), ``data/processed/forecast/*`` (models + feature_spec.json), and writes
``src/vendor/data/grid_hours.parquet`` (EIA-930 + curtailment in the ``GridHour`` schema, ``ts`` =
slot END in UTC). ``src/vendor/`` is generated: it is gitignored.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import pandas as pd

CHALK_DIR = Path(__file__).resolve().parent
BACKEND = CHALK_DIR.parent
sys.path.insert(0, str(BACKEND))

from clearinghouse.data import load_curtailment, load_eia930  # noqa: E402

VENDOR = CHALK_DIR / "src" / "vendor"
SRC = BACKEND / "clearinghouse" / "forecast"
REWRITES = {
    "from clearinghouse.config import DATA_PROCESSED":
        "DATA_PROCESSED = Path(__file__).resolve().parent  # vendored copy (sync_from_app.py)",
    "from clearinghouse.forecast import features as F": "from . import features as F",
}


def main() -> None:
    spec = json.loads((BACKEND / "data" / "processed" / "forecast" / "feature_spec.json")
                      .read_text())
    if spec.get("model_set", "M4") != "M4":
        # M10 models read forecast inputs (ERCOT postings, Open-Meteo forecasts) indexed by valid
        # time; the Chalk resolvers only serve history with ts <= now, so they would get NaN.
        raise SystemExit("the default forecast artifacts are M10 (forecast inputs), which this "
                         "Chalk project does not serve yet; src/vendor/ keeps the M4 snapshot")
    if VENDOR.exists():
        shutil.rmtree(VENDOR)
    (VENDOR / "data").mkdir(parents=True)
    (VENDOR / "__init__.py").write_text('"""Generated by sync_from_app.py. Do not edit."""\n')
    for name in ("features.py", "model.py", "provider.py"):
        text = (SRC / name).read_text()
        for old, new in REWRITES.items():
            text = text.replace(old, new)
        if "clearinghouse" in "\n".join(line for line in text.splitlines()
                                         if line.startswith(("from ", "import "))):
            raise SystemExit(f"{name}: unvendored clearinghouse import left")
        (VENDOR / name).write_text(text)
    shutil.copytree(BACKEND / "data" / "processed" / "forecast", VENDOR / "artifacts")

    e = load_eia930()
    c = load_curtailment()[["ts_utc", "wind_curtailed_mw", "solar_curtailed_mw"]]
    h = e.merge(c, on="ts_utc", how="left")
    out = pd.DataFrame({
        "id": "ERCO:" + h["ts_cst"].dt.strftime("%Y-%m-%dT%H"),
        "region": "ERCO",
        "ts": h["ts_utc"] + pd.Timedelta(hours=1),  # slot END: when the value is known
        "hour_cst": h["hour_cst"].astype(int),
        "demand_mw": h["demand_mw"], "wind_mw": h["wind_mw"], "solar_mw": h["solar_mw"],
        "nuclear_mw": h["nuclear_mw"], "hydro_mw": h["hydro_mw"], "other_mw": h["other_mw"],
        "storage_mw": h["storage_mw"].fillna(0.0),
        "net_imports_mw": -h["interchange_mw"],
        "wind_curtailed_mw": h["wind_curtailed_mw"], "solar_curtailed_mw": h["solar_curtailed_mw"],
    })
    out.to_parquet(VENDOR / "data" / "grid_hours.parquet", index=False)
    print(f"vendored code + artifacts + {len(out)} hourly rows into {VENDOR}")


if __name__ == "__main__":
    main()
